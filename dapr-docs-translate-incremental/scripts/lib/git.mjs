// Git helpers for the dapr-docs-* skills. Node built-ins only.
// Copied verbatim into every skill's scripts/lib/ (tests/shared-lib-sync.test.mjs keeps the copies identical).
// Every git call goes through an injectable `exec(file, args, {cwd})` so tests run without a remote.
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { normRel } from "./config.mjs";

/** Default exec: runs a program with no shell and never waits on a credential prompt. */
export const spawnExec = (file, args, { cwd, env, input } = {}) => {
  const r = spawnSync(file, args, {
    cwd,
    env: { ...process.env, GIT_TERMINAL_PROMPT: "0", ...(env ?? {}) },
    input,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  return { status: r.status, signal: r.signal ?? null, stdout: r.stdout ?? "", stderr: r.stderr ?? "", error: r.error ? r.error.message : null };
};

/**
 * Parses `git status --porcelain=v1 -z`. Each record is `XY PATH`; a rename or copy is followed by one more
 * NUL-separated field with the original path, which is kept as `from`.
 */
export function parsePorcelainZ(text) {
  const parts = String(text).split("\0");
  const out = [];
  for (let i = 0; i < parts.length; i += 1) {
    const rec = parts[i];
    if (rec === "") continue;
    const x = rec[0];
    const y = rec[1];
    let from = null;
    if ("RC".includes(x) || "RC".includes(y)) {
      i += 1;
      from = parts[i] ?? null;
    }
    out.push({
      x,
      y,
      path: rec.slice(3),
      from,
      staged: x !== " " && x !== "?" && x !== "!",
      unstaged: y !== " " && y !== "?" && y !== "!",
      untracked: x === "?" && y === "?",
    });
  }
  return out;
}

/** Runs `git status` read-only. --no-optional-locks keeps it from refreshing the index. */
export function statusEntries(exec, cwd) {
  const r = exec("git", ["--no-optional-locks", "status", "--porcelain=v1", "-z", "--untracked-files=all"], { cwd });
  if (r.status !== 0) throw new Error(`git status failed in ${cwd}: ${r.stderr || r.error || `exit ${r.status}`}`);
  return parsePorcelainZ(r.stdout);
}

/** Every path an entry touches: the path itself and, for a rename, the original. */
export const touchedPaths = (entry) => [entry.path, entry.from].filter(Boolean);

/** True when `p` is `scope` or lies inside it. `scope` is a directory (`translations/`) or a file. */
export function inScope(p, scopes) {
  return scopes.some((s) => {
    const n = normRel(s);
    return p === n || p.startsWith(`${n}/`);
  });
}

/**
 * Sorts changed paths into three buckets: inside writeScope, inside syncOutputPaths (generated by a sync,
 * committed by hand), and everything else. Renames count both paths.
 */
export function classify(entries, { writeScope = [], syncOutputPaths = [] } = {}) {
  const out = { inScope: [], sync: [], outOfScope: [] };
  for (const entry of entries) {
    for (const p of touchedPaths(entry)) {
      const bucket = inScope(p, writeScope) ? "inScope" : inScope(p, syncOutputPaths) ? "sync" : "outOfScope";
      out[bucket].push({ path: p, status: `${entry.x}${entry.y}`, staged: entry.staged, untracked: entry.untracked });
    }
  }
  return out;
}

/** A stable digest of the working tree status: the same changes give the same digest, whatever the order. */
export function statusDigest(entries) {
  const lines = entries.map((e) => `${e.x}${e.y} ${e.path}${e.from ? ` <- ${e.from}` : ""}`).sort();
  return createHash("sha256").update(lines.join("\n")).digest("hex");
}

export function headCommit(exec, cwd) {
  const r = exec("git", ["rev-parse", "HEAD"], { cwd });
  if (r.status !== 0) throw new Error(`git rev-parse HEAD failed in ${cwd}: ${r.stderr || r.error || `exit ${r.status}`}`);
  return r.stdout.trim();
}
